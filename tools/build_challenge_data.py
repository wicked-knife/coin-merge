"""Embed the captured challenge tables so exported builds do not depend on docs/."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "docs/rea-reference"
levels = json.loads((REFERENCE / "challenge-levels-expanded.json").read_text(encoding="utf-8"))
rows = []
for entry in levels:
    config = entry["config"]
    rows.append({"columns": config["row"], "rows": config["column"],
                 "unlock": config["unlockNumeral"],
                 "hidden": [int(x) for x in config["greyNum"].split("#")],
                 "targets": entry["target_layout_linear"]})
weights = json.loads((REFERENCE / "configs/Excelchallenge_deal1.json").read_text(encoding="utf-8"))
tables = [[[int(x) for x in row[f"challenge{index}"].split("#")] for row in weights]
          for index in range(1, 7)]
source = ('extends RefCounted\n'
          '# Generated by tools/build_challenge_data.py from the captured release tables.\n'
          '# Config row is the horizontal slot count; column is the vertical count.\n'
          'const LEVELS := [\n')
source += "".join("\t" + json.dumps(row, separators=(",", ":")) + ",\n" for row in rows)
source += "]\n\nconst GROUP_WEIGHTS := " + json.dumps(tables) + "\n"
(ROOT / "scripts/challenge_data.gd").write_text(source, encoding="utf-8")
print(f"Embedded {len(rows)} challenge levels and {len(tables)} group tables.")
