"""Convert captured Cocos clip fields to inert Godot constants; never execute the bundle."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def typed(value, kind):
    if kind == 8:  # Cocos ValueType: first element identifies the value type.
        return value[1:]
    if kind == 12:  # Array with per-entry serialized type tags.
        return [typed(item, tag) for item, tag in zip(value[0], value[1:])]
    return unpack(value)


def unpack(value):
    if isinstance(value, dict):
        return {key: unpack(item) for key, item in value.items()}
    if isinstance(value, list):
        if len(value) >= 4 and isinstance(value[0], dict) and isinstance(value[1], str):
            result = unpack(value[0])
            for index in range(1, len(value), 3):
                key, kind, item = value[index:index + 3]
                result[key] = typed(item, kind)
            return result
        return [unpack(item) for item in value]
    return value


clips = {}
for file in sorted((ROOT / "assets/rea_original/reference/cocos_animation_clips").glob("*.json")):
    source = json.loads(file.read_text(encoding="utf-8"))
    attrs = source["attributes"]
    curves = unpack(attrs.get("curveData", {}))
    tracks = {}
    for prop, frames in curves.get("props", {}).items():
        if frames:
            tracks["|" + prop] = frames
    for path, node in curves.get("paths", {}).items():
        for prop, frames in node.get("props", {}).items():
            if frames:
                tracks[path + "|" + prop] = frames
    clips[attrs["_name"]] = {"duration": attrs.get("_duration", 0), "loop": attrs.get("wrapMode") == 2, "tracks": tracks}

output = ROOT / "scripts/normal_motion_data.gd"
output.write_text("extends RefCounted\n# Generated by tools/build_normal_motion.py from captured Cocos AnimationClips.\nconst CLIPS = " + json.dumps(clips, ensure_ascii=False, indent="\t") + "\n", encoding="utf-8")
for name, clip in clips.items():
    print(name, clip["duration"], list(clip["tracks"]))
