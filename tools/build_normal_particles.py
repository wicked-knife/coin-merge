"""Extract inert particle descriptions from captured Cocos prefabs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'assets/rea_original/reference/cocos-published/assets/resources/import'
SOURCES = {
    'reveal': ('e6/e670cabe-f486-47cb-87d8-d3ec501274fe.json', ['ui/Light1.png']),
    'ready': ('0f/0f5c7c6cd.json', ['../particles/atom.texture.png']),
    'firework': ('07/070775b95.json', ['ui/Pieces1.png', 'ui/Pieces2.png']),
    'combo': ('0f/0fb55d1b1.json', ['ui/Light1.png']),
    'bigcoin': ('0e/0e9a58c3e.json', ['ui/Light1.png']),
}
result = {}
for kind, (path, textures) in SOURCES.items():
    doc = json.loads((BASE / path).read_text(encoding='utf-8'))
    found = []

    def walk(value):
        if not isinstance(value, list):
            return
        if value and type(value[0]) is int and 0 <= value[0] < len(doc[4]):
            mask = doc[4][value[0]]
            cls = doc[3][mask[0]]
            if isinstance(cls, list) and cls[0] == 'cc.ParticleSystem' and len(value) >= len(mask) - 1:
                record = {cls[1][i]: v for i, v in zip(mask[1:-1], value[1:])}
                for field in ['node', '_materials', '_spriteFrame', '_file', 'spriteFrame']:
                    record.pop(field, None)
                record['texture'] = textures[len(found)]
                found.append(record)
                return
        for item in value:
            walk(item)

    walk(doc[5])
    assert len(found) == len(textures), (kind, found)
    result[kind] = found
(ROOT / 'scripts/normal_particle_data.gd').write_text(
    'extends RefCounted\n# Generated by tools/build_normal_particles.py; values retain Cocos units.\nconst EMITTERS = '
    + json.dumps(result, ensure_ascii=False, indent='\t') + '\n', encoding='utf-8')
